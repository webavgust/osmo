-- ---------------------------------------------------------------------------
-- Патч v27: статусы КП — только «В работе», «Выиграно», «Проиграно»
--
-- «Заморожено» (frozen) и «Отменено» (canceled) больше не статусы, а причины
-- проигрыша (ProposalLostReason::FROZEN / CANCELED, коды те же).
--
-- Перевод записей: status → 'lost', status_reason → прежний статус.
-- Прежняя причина (у таких КП она обязательна) не теряется — дописывается
-- в начало комментария: «Прежняя причина: Дорого». Комментарий — varchar(500).
--
-- Статус пишется во все редакции группы, поэтому обновляем все строки.
-- Запрос идемпотентный: повторный прогон ничего не меняет.
-- ---------------------------------------------------------------------------

UPDATE `proposals`
SET `status_comment` = LEFT(
        CONCAT_WS('. ',
            CASE `status_reason`
                WHEN 'price' THEN 'Прежняя причина: Дорого'
                WHEN 'competitor' THEN 'Прежняя причина: Ушли к конкуренту'
                WHEN 'budget' THEN 'Прежняя причина: Нет бюджета'
                WHEN 'timeline' THEN 'Прежняя причина: Сроки'
                WHEN 'functional' THEN 'Прежняя причина: Не хватило функционала'
                WHEN 'no_need' THEN 'Прежняя причина: Отпала потребность'
                WHEN 'no_response' THEN 'Прежняя причина: Заказчик не отвечает'
                WHEN 'internal' THEN 'Прежняя причина: Наше решение'
                WHEN 'other' THEN 'Прежняя причина: Другое'
                ELSE NULL
            END,
            NULLIF(`status_comment`, '')
        ), 500),
    `status_reason` = `status`,
    `status` = 'lost'
WHERE `status` IN ('frozen', 'canceled');
