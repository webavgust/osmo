-- ---------------------------------------------------------------------------
-- Патч v30: константы рабочего стола
--
-- Пока одна: белый список доменов для виджета «Внешняя страница». Пустое
-- значение означает «встраивать нечего» — виджет об этом прямо говорит и
-- чужую страницу не открывает. Домены перечисляются через запятую, поддомены
-- считаются разрешёнными автоматически (bitrix24.ru разрешает
-- company.bitrix24.ru).
--
-- Запрос идемпотентный: константа добавляется, только если её ещё нет.
-- После выполнения — php artisan cache:clear (константы кэшируются).
-- ---------------------------------------------------------------------------

SET NAMES utf8mb4;

INSERT INTO `consts` (`name`, `key`, `value`, `note`, `system`)
SELECT 'Рабочий стол: разрешённые домены для встраивания', 'desktop_embed_domains', '',
       'Домены через запятую, страницы которых можно вставлять виджетом «Внешняя страница» на рабочем столе (например bitrix24.ru, metrika.yandex.ru). Поддомены разрешаются сами. Пусто — встраивание выключено.', 0
FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM `consts` WHERE `key` = 'desktop_embed_domains');
